export function notesToShow(rows) {
  if (!Array.isArray(rows) || rows.length === 0) return BUNDLED_NOTES;
  return rows.filter((row) => row && !row.deleted_at && !row.archived);
}

export function noteForVariety(rows, variety) {
  const alive = notesToShow(rows).filter((row) => row?.variety);
  const full = varietyFull(variety);
  if (!full) return null;
  const exact = alive.find((row) => varietyFull(row.variety) === full);
  if (exact) return exact;
  const key = varietyKey(variety);
  if (!key || key === full) return null;
  return alive.find((row) => varietyFull(row.variety) === key) || null;
}
